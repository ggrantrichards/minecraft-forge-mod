def guardian_ring(face, px, py, fw, fh, rnd):
    if face not in ("up", "down"):
        return None
    cx, cy = (fw - 1) / 2, (fh - 1) / 2
    r = math.hypot(px - cx, py - cy)
    if r < 5.2 or r > 9.8:
        return None
    t = (r - 5.2) / 4.6
    c = mix(hexc("fff0ff"), hexc("ff7ab8"), min(1, t * 1.4))
    c = mix(c, hexc("8a3cff"), max(0, t - 0.5))
    if rnd.random() < 0.15:
        c = mix(c, hexc("ffffff"), 0.5)
    return c


