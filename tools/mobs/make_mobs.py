def _hg_hash(face, px, py, fw, fh):
    h = (px * 73856093) ^ (py * 19349663) ^ (fw * 83492791) ^ (fh * 2654435761) ^ (ord(face[0]) * 97)
    h = (h ^ (h >> 13)) * 1274126177
    return ((h ^ (h >> 16)) & 0xFFFF) / 65536.0


