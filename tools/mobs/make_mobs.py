def crust(px, py):
    """The Skimmer's camouflage: the same cracked, sun-baked crust as the Corona's ground."""
    t = n()
    if 0.48 < t < 0.53:
        return K_CRUST[0]                      # a crack
    return K_CRUST[1 + min(3, int(t * 4))]


