P_TENDRIL = [hexc("b48cf0", 230), hexc("9a72e0", 230)]


def pollinator_bell(face, px, py, fw, fh, rnd):
    c = rnd.choice(P_BELL)
    if face in ("north", "south", "east", "west"):
        c = mix(c, hexc("c9fff6", 215), max(0.0, 0.5 - py / max(1, fh)))
    if face == "up":
        c = mix(c, hexc("d9fff8", 215), 0.4)
    if face == "down":
        c = hexc("3d7f8a", 200)
    return c


def pollinator_bell_glow(face, px, py, fw, fh, rnd):
    if face in ("north", "south", "east", "west") and (px + py * 2) % 5 == 0 and py >= 1:
        return hexc("e6fffa")
    if face == "up" and (px * 3 + py) % 7 == 0:
        return hexc("c8fff5")
    return None


def pollinator_tendril(face, px, py, fw, fh, rnd):
    if face in ("up", "down"):
        return P_TENDRIL[0]
    return rnd.choice(P_TENDRIL)


def pollinator_tendril_glow(face, px, py, fw, fh, rnd):
    if face in ("north", "south", "east", "west") and py >= fh - 2:
        return hexc("f2d8ff")
    return None


