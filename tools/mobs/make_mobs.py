#!/usr/bin/env python3
"""Models and textures for the mobs of The Astral End (Phase 4).

Each mob's model is described once, here: its parts, and the boxes in each part with their
texture offsets. From that one description this script writes

  - src/main/java/com/ggrantrichards/astralend/client/model/MobMeshes.java, the model geometry
    (the LayerDefinitions the game bakes), and
  - the textures, painted box by box onto the same UV layout the game uses, so they always line
    up: textures/entity/<mob>/<mob>.png, a <mob>_glow.png for the parts that shine in the dark,
    and the spawn egg icons.

Run it after changing a model:  python3 tools/mobs/make_mobs.py   (needs Pillow)

Coordinates are Minecraft's model units: 16 to a block, y pointing down, the ground at y = 24.
A mob faces -z ("north") in its model; the front of a box is its north face.
"""
import math
import random
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
JAVA = ROOT / "src/main/java/com/ggrantrichards/astralend/client/model/MobMeshes.java"
TEX = ROOT / "src/main/resources/assets/astralend/textures"


def hexc(h, a=255):
    h = h.lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)


def mix(a, b, t):
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(4))


# ------------------------------------------------------------------ model description

class Box:
    def __init__(self, u, v, x, y, z, w, h, d, mirror=False, paint=None, glow=None, inflate=0.0):
        self.inflate = inflate  # grows the box without changing its texture size, like vanilla's overlays
        self.u, self.v = u, v
        self.x, self.y, self.z = x, y, z
        self.w, self.h, self.d = w, h, d
        self.mirror = mirror
        self.paint = paint  # fn(face, px, py, fw, fh, rnd) -> colour or None
        self.glow = glow    # same, for the glow texture

    def faces(self):
        """Texture rectangles of the six faces: name -> (x, y, width, height)."""
        u, v, w, h, d = self.u, self.v, self.w, self.h, self.d
        return {
            "up": (u + d, v, w, d),
            "down": (u + d + w, v, w, d),
            "east": (u, v + d, d, h),       # the mob's left side as you look at its face
            "north": (u + d, v + d, w, h),  # the front
            "west": (u + d + w, v + d, d, h),
            "south": (u + d + w + d, v + d, w, h),
        }


class Part:
    def __init__(self, name, pose, boxes=(), children=()):
        self.name = name
        self.pose = pose  # (x, y, z) or (x, y, z, xRot, yRot, zRot)
        self.boxes = list(boxes)
        self.children = list(children)


class Mob:
    def __init__(self, name, size, parts, egg, halo=None, clear=()):
        self.halo = halo  # a faint colour added round every glowing pixel (a soft bioluminescent bloom)
        self.clear = {c[:3] for c in clear}  # colours (eyes) the bloom keeps off and doesn't spread from
        self.name = name
        self.size = size  # texture width, height
        self.parts = parts
        self.egg = egg    # (base, spots) colours of the spawn egg


def fnum(x):
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return (s if "." in s else s + ".0") + "F"


def java_part(part, parent_var, out, indent):
    pad = " " * indent
    cubes = "CubeListBuilder.create()"
    for b in part.boxes:
        cubes += f".texOffs({b.u}, {b.v})"
        if b.mirror:
            cubes += ".mirror()"
        deform = f", new CubeDeformation({fnum(b.inflate)})" if b.inflate else ""
        cubes += f".addBox({fnum(b.x)}, {fnum(b.y)}, {fnum(b.z)}, {fnum(b.w)}, {fnum(b.h)}, {fnum(b.d)}{deform})"
        if b.mirror:
            cubes += ".mirror(false)"
    p = part.pose
    if len(p) == 3:
        pose = f"PartPose.offset({fnum(p[0])}, {fnum(p[1])}, {fnum(p[2])})"
    else:
        pose = "PartPose.offsetAndRotation(" + ", ".join(fnum(c) for c in p) + ")"
    var = part.name.replace("-", "_")
    if part.children:
        out.append(f"{pad}PartDefinition {var} = {parent_var}.addOrReplaceChild(\"{part.name}\", {cubes}, {pose});")
        for c in part.children:
            java_part(c, var, out, indent)
    else:
        out.append(f"{pad}{parent_var}.addOrReplaceChild(\"{part.name}\", {cubes}, {pose});")


def write_java(mobs):
    lines = [
        "package com.ggrantrichards.astralend.client.model;",
        "",
        "import net.minecraft.client.model.geom.PartPose;",
        "import net.minecraft.client.model.geom.builders.CubeDeformation;",
        "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
        "import net.minecraft.client.model.geom.builders.LayerDefinition;",
        "import net.minecraft.client.model.geom.builders.MeshDefinition;",
        "import net.minecraft.client.model.geom.builders.PartDefinition;",
        "",
        "// GENERATED by tools/mobs/make_mobs.py - edit the model there, not here. The script paints",
        "// the textures onto the same boxes, so the two always match.",
        "public final class MobMeshes {",
    ]
    for mob in mobs:
        method = "".join(w.capitalize() if i else w for i, w in enumerate(mob.name.split("_")))
        lines.append(f"    public static LayerDefinition {method}() {{")
        lines.append("        MeshDefinition mesh = new MeshDefinition();")
        lines.append("        PartDefinition root = mesh.getRoot();")
        body = []
        for part in mob.parts:
            java_part(part, "root", body, 8)
        lines += body
        lines.append(f"        return LayerDefinition.create(mesh, {mob.size[0]}, {mob.size[1]});")
        lines.append("    }")
        lines.append("")
    lines.append("    private MobMeshes() {}")
    lines.append("}")
    JAVA.parent.mkdir(parents=True, exist_ok=True)
    JAVA.write_text("\n".join(lines) + "\n")


def auto_uv(mob):
    """Gives every box whose u is None a place on the texture (shelf packing, tallest first).
    Boxes with the same `uv_key` share one area (mirrored limbs)."""
    boxes = [b for b in all_boxes(mob.parts) if b.u is None]
    shared = {}
    todo = []
    for b in boxes:
        key = getattr(b, "uv_key", None) or id(b)
        if key not in shared:
            shared[key] = []
            todo.append((key, b))
        shared[key].append(b)
    def footprint(b):
        return int(math.ceil(2 * (b.d + b.w))), int(math.ceil(b.d + b.h))
    todo.sort(key=lambda kb: (-footprint(kb[1])[1], -footprint(kb[1])[0]))
    sky = [0] * mob.size[0]                   # skyline: the lowest free row in each column
    for key, b in todo:
        w, h = footprint(b)
        best = None
        for x in range(0, mob.size[0] - w + 1):
            y = max(sky[x:x + w])
            if y + h <= mob.size[1] and (best is None or y < best[1]):
                best = (x, y)
        if best is None:
            raise ValueError(f"{mob.name}: texture {mob.size} too small for its boxes")
        x, y = best
        for i in range(x, x + w):
            sky[i] = y + h
        for other in shared[key]:
            other.u, other.v = x, y


def all_boxes(parts):
    for p in parts:
        yield from p.boxes
        yield from all_boxes(p.children)


# While a mob is painted: the texture pixel being painted, and smooth noise over the whole texture,
# so painters can shade coherently (mottling in patches) instead of pixel by pixel.
CUR = {"x": 0, "y": 0, "noise": None}


def smooth_noise(w, h, seed, cell=4):
    rnd = random.Random(seed)
    gw, gh = w // cell + 2, h // cell + 2
    lattice = [[rnd.random() for _ in range(gw)] for _ in range(gh)]
    out = [[0.0] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            gx, gy = x / cell, y / cell
            x0, y0 = int(gx), int(gy)
            tx, ty = gx - x0, gy - y0
            tx, ty = tx * tx * (3 - 2 * tx), ty * ty * (3 - 2 * ty)
            a, b = lattice[y0][x0], lattice[y0][x0 + 1]
            c, d = lattice[y0 + 1][x0], lattice[y0 + 1][x0 + 1]
            out[y][x] = (a + (b - a) * tx) * (1 - ty) + (c + (d - c) * tx) * ty
    return out


def n():
    """Smooth noise (0..1) at the pixel being painted."""
    return CUR["noise"][CUR["y"]][CUR["x"]]


def paint_mob(mob, seed):
    CUR["noise"] = smooth_noise(mob.size[0], mob.size[1], seed)
    img = Image.new("RGBA", mob.size, (0, 0, 0, 0))
    glow = Image.new("RGBA", mob.size, (0, 0, 0, 0))
    has_glow = False
    rnd = random.Random(seed)
    done = set()
    for b in all_boxes(mob.parts):
        key = (b.u, b.v, b.w, b.h, b.d)
        if key in done:  # boxes that share a texture area are painted once
            continue
        done.add(key)
        for face, (fx, fy, fw, fh) in b.faces().items():
            for py in range(int(fh)):
                for px in range(int(fw)):
                    x, y = int(fx) + px, int(fy) + py
                    if not (0 <= x < mob.size[0] and 0 <= y < mob.size[1]):
                        continue
                    CUR["x"], CUR["y"] = x, y
                    if b.paint:
                        c = b.paint(face, px, py, int(fw), int(fh), rnd)
                        if c is not None:
                            img.putpixel((x, y), c)
                    if b.glow:
                        g = b.glow(face, px, py, int(fw), int(fh), rnd)
                        if g is not None:
                            glow.putpixel((x, y), g)
                            has_glow = True
    if has_glow and mob.halo:
        add_halo(img, glow, mob.halo, mob.clear)
    return img, (glow if has_glow else None)


def add_halo(img, glow, colour, clear=frozenset()):
    """The glow layer is drawn additively (like a spider's eyes), so a dim colour round each light
    reads as a soft bloom of light on the skin around it."""
    g = glow.load()
    lit = {(x, y) for y in range(glow.height) for x in range(glow.width) if g[x, y][3]}
    for (x, y) in lit:
        if g[x, y][:3] in clear:
            continue
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            q = (x + dx, y + dy)
            if (q not in lit and 0 <= q[0] < glow.width and 0 <= q[1] < glow.height and img.getpixel(q)[3]
                    and img.getpixel(q)[:3] not in clear):
                g[q] = colour


# ------------------------------------------------------------------ painters

def B(x, y, z, w, h, d, paint=None, glow=None, key=None, mirror=False, inflate=0.0):
    """A box placed on the texture automatically (auto_uv). Boxes with the same key share one area."""
    b = Box(None, None, x, y, z, w, h, d, mirror=mirror, paint=paint, glow=glow, inflate=inflate)
    b.uv_key = key
    return b


def shade_flat(face):
    """Vanilla-style face shading: top a shade lighter, bottom darker, sides the base."""
    return {"up": 1, "down": -1}.get(face, 0)


def clamp(i, pal):
    return pal[max(0, min(len(pal) - 1, i))]


def dith(pal, base=1, var=0.3, patch=0.72, light_top=True, dark=False):
    """Vanilla-style fill: one main tone, a few lighter/darker pixels, lighter patches, top lit."""
    def f(face, px, py, fw, fh, rnd):
        i = base + (shade_flat(face) if light_top else 0)
        v = n()
        if v > patch:
            i += 1                                            # soft lighter patches
        elif dark and v < 1 - patch - 0.05:
            i -= 1                                            # and darker ones
        r = rnd.random()
        k = var * 0.4                                         # only a few single-pixel specks
        if r < k / 2:
            i -= 1
        elif r < k:
            i += 1
        return clamp(i, pal)
    return f


def mirror_rows(rows):
    return [r[::-1] for r in rows]


def art(faces, pal, base=None):
    """Hand-drawn pixel art per face; '.' falls through to the base painter, ' ' is transparent."""
    def f(face, px, py, fw, fh, rnd):
        rows = faces.get(face)
        if rows is not None and py < len(rows) and px < len(rows[py]):
            ch = rows[py][px]
            if ch == " ":
                return None
            if ch in pal:
                c = pal[ch]
                return c(face, px, py, fw, fh, rnd) if callable(c) else c
        return base(face, px, py, fw, fh, rnd) if base else None
    return f


def glow_art(faces, pal):
    def f(face, px, py, fw, fh, rnd):
        rows = faces.get(face)
        if rows is not None and py < len(rows) and px < len(rows[py]):
            return pal.get(rows[py][px])
        return None
    return f


def sides(east_rows):
    """East and west faces of a symmetric part (east runs back->front, west front->back)."""
    return {"east": east_rows, "west": mirror_rows(east_rows)}



def speckled(colours, weights=None, top=None, bottom=None):
    """Random pixels from a palette, lighter on top and darker underneath."""
    def f(face, px, py, fw, fh, rnd):
        c = rnd.choices(colours, weights=weights)[0]
        if face == "up" and top:
            c = mix(c, top, 0.35)
        if face == "down" and bottom:
            c = mix(c, bottom, 0.45)
        return c
    return f


def solid(colour):
    return lambda face, px, py, fw, fh, rnd: colour


def edge_dist(px, py, fw, fh):
    return min(px, py, fw - 1 - px, fh - 1 - py)


