    if face == "down":
        return False
    if face == "up":
        density = 0.08
    elif face in ("east", "west"):
        density = 0.07 if py < fh * 0.55 else 0.015
    else:
        density = 0.03
    return _hg_hash(face, px, py, fw, fh) < density


