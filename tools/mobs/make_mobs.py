#!/usr/bin/env python3
"""Models and textures for the mobs of The Astral End (Phase 4).

Each mob's model is described once, here: its parts, and the boxes in each part with their
texture offsets. From that one description this script writes

  - src/main/java/com/ggrantrichards/astralend/client/model/MobMeshes.java, the model geometry
    (the LayerDefinitions the game bakes), and
  - the textures, painted box by box onto the same UV layout the game uses, so they always line
    up: textures/entity/<mob>/<mob>.png, a <mob>_glow.png for the parts that shine in the dark,
    and the spawn egg icons.

Run it after changing a model:  python3 tools/mobs/make_mobs.py   (needs Pillow)

Coordinates are Minecraft's model units: 16 to a block, y pointing down, the ground at y = 24.
A mob faces -z ("north") in its model; the front of a box is its north face.
"""
import math
import random
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
JAVA = ROOT / "src/main/java/com/ggrantrichards/astralend/client/model/MobMeshes.java"
TEX = ROOT / "src/main/resources/assets/astralend/textures"


def hexc(h, a=255):
    h = h.lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)


def mix(a, b, t):
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(4))


# ------------------------------------------------------------------ model description

class Box:
    def __init__(self, u, v, x, y, z, w, h, d, mirror=False, paint=None, glow=None):
        self.u, self.v = u, v
        self.x, self.y, self.z = x, y, z
        self.w, self.h, self.d = w, h, d
        self.mirror = mirror
        self.paint = paint  # fn(face, px, py, fw, fh, rnd) -> colour or None
        self.glow = glow    # same, for the glow texture

    def faces(self):
        """Texture rectangles of the six faces: name -> (x, y, width, height)."""
        u, v, w, h, d = self.u, self.v, self.w, self.h, self.d
        return {
            "up": (u + d, v, w, d),
            "down": (u + d + w, v, w, d),
            "east": (u, v + d, d, h),       # the mob's left side as you look at its face
            "north": (u + d, v + d, w, h),  # the front
            "west": (u + d + w, v + d, d, h),
            "south": (u + d + w + d, v + d, w, h),
        }


class Part:
    def __init__(self, name, pose, boxes=(), children=()):
        self.name = name
        self.pose = pose  # (x, y, z) or (x, y, z, xRot, yRot, zRot)
        self.boxes = list(boxes)
        self.children = list(children)


class Mob:
    def __init__(self, name, size, parts, egg):
        self.name = name
        self.size = size  # texture width, height
        self.parts = parts
        self.egg = egg    # (base, spots) colours of the spawn egg


def fnum(x):
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return (s if "." in s else s + ".0") + "F"


def java_part(part, parent_var, out, indent):
    pad = " " * indent
    cubes = "CubeListBuilder.create()"
    for b in part.boxes:
        cubes += f".texOffs({b.u}, {b.v})"
        if b.mirror:
            cubes += ".mirror()"
        cubes += f".addBox({fnum(b.x)}, {fnum(b.y)}, {fnum(b.z)}, {fnum(b.w)}, {fnum(b.h)}, {fnum(b.d)})"
        if b.mirror:
            cubes += ".mirror(false)"
    p = part.pose
    if len(p) == 3:
        pose = f"PartPose.offset({fnum(p[0])}, {fnum(p[1])}, {fnum(p[2])})"
    else:
        pose = "PartPose.offsetAndRotation(" + ", ".join(fnum(c) for c in p) + ")"
    var = part.name.replace("-", "_")
    if part.children:
        out.append(f"{pad}PartDefinition {var} = {parent_var}.addOrReplaceChild(\"{part.name}\", {cubes}, {pose});")
        for c in part.children:
            java_part(c, var, out, indent)
    else:
        out.append(f"{pad}{parent_var}.addOrReplaceChild(\"{part.name}\", {cubes}, {pose});")


def write_java(mobs):
    lines = [
        "package com.ggrantrichards.astralend.client.model;",
        "",
        "import net.minecraft.client.model.geom.PartPose;",
        "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
        "import net.minecraft.client.model.geom.builders.LayerDefinition;",
        "import net.minecraft.client.model.geom.builders.MeshDefinition;",
        "import net.minecraft.client.model.geom.builders.PartDefinition;",
        "",
        "// GENERATED by tools/mobs/make_mobs.py - edit the model there, not here. The script paints",
        "// the textures onto the same boxes, so the two always match.",
        "public final class MobMeshes {",
    ]
    for mob in mobs:
        method = "".join(w.capitalize() if i else w for i, w in enumerate(mob.name.split("_")))
        lines.append(f"    public static LayerDefinition {method}() {{")
        lines.append("        MeshDefinition mesh = new MeshDefinition();")
        lines.append("        PartDefinition root = mesh.getRoot();")
        body = []
        for part in mob.parts:
            java_part(part, "root", body, 8)
        lines += body
        lines.append(f"        return LayerDefinition.create(mesh, {mob.size[0]}, {mob.size[1]});")
        lines.append("    }")
        lines.append("")
    lines.append("    private MobMeshes() {}")
    lines.append("}")
    JAVA.parent.mkdir(parents=True, exist_ok=True)
    JAVA.write_text("\n".join(lines) + "\n")


def all_boxes(parts):
    for p in parts:
        yield from p.boxes
        yield from all_boxes(p.children)


def paint_mob(mob, seed):
    img = Image.new("RGBA", mob.size, (0, 0, 0, 0))
    glow = Image.new("RGBA", mob.size, (0, 0, 0, 0))
    has_glow = False
    rnd = random.Random(seed)
    done = set()
    for b in all_boxes(mob.parts):
        key = (b.u, b.v, b.w, b.h, b.d)
        if key in done:  # boxes that share a texture area are painted once
            continue
        done.add(key)
        for face, (fx, fy, fw, fh) in b.faces().items():
            for py in range(int(fh)):
                for px in range(int(fw)):
                    x, y = int(fx) + px, int(fy) + py
                    if not (0 <= x < mob.size[0] and 0 <= y < mob.size[1]):
                        continue
                    if b.paint:
                        c = b.paint(face, px, py, int(fw), int(fh), rnd)
                        if c is not None:
                            img.putpixel((x, y), c)
                    if b.glow:
                        g = b.glow(face, px, py, int(fw), int(fh), rnd)
                        if g is not None:
                            glow.putpixel((x, y), g)
                            has_glow = True
    return img, (glow if has_glow else None)


# ------------------------------------------------------------------ painters

def speckled(colours, weights=None, top=None, bottom=None):
    """Random pixels from a palette, lighter on top and darker underneath."""
    def f(face, px, py, fw, fh, rnd):
        c = rnd.choices(colours, weights=weights)[0]
        if face == "up" and top:
            c = mix(c, top, 0.35)
        if face == "down" and bottom:
            c = mix(c, bottom, 0.45)
        return c
    return f


def solid(colour):
    return lambda face, px, py, fw, fh, rnd: colour


def edge_dist(px, py, fw, fh):
    return min(px, py, fw - 1 - px, fh - 1 - py)


