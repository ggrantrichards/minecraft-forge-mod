def egg(base, spots):
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    pal = {
        "o": mix(base, hexc("000000"), 0.65),
        "b": base,
        "d": mix(base, hexc("000000"), 0.3),
        "h": mix(base, hexc("ffffff"), 0.45),
        "s": spots,
    }
    for y, row in enumerate(EGG):
        for x, ch in enumerate(row):
            if ch != ".":
                img.putpixel((x, y), pal[ch])
    return img


